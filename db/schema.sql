-- Crown & Co. Events — Neon (Postgres) schema.
-- Idempotent: safe to re-run with `npm run db:migrate`.

CREATE TABLE IF NOT EXISTS bookings (
  id            text PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  status        text NOT NULL,
  package_slug  text NOT NULL,
  event_date    date NOT NULL,
  guests        integer NOT NULL,
  amount_paid   integer NOT NULL,
  total         integer NOT NULL,
  phone         text NOT NULL,
  email         text NOT NULL,
  anonymous_id  text,
  session_id    text,
  data          jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS bookings_created_at_idx ON bookings (created_at DESC);

CREATE TABLE IF NOT EXISTS enquiries (
  id            text PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  status        text NOT NULL DEFAULT 'new',
  source        text NOT NULL,
  package_slug  text,
  category      text,
  destination   text,
  phone         text NOT NULL,
  anonymous_id  text,
  session_id    text,
  data          jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS enquiries_created_at_idx ON enquiries (created_at DESC);

CREATE TABLE IF NOT EXISTS otps (
  phone       text PRIMARY KEY,
  code        text NOT NULL,
  expires_at  timestamptz NOT NULL
);

-- One row per tracked interaction. Common dimensions are columns (fast to filter / group by);
-- event-specific fields live in `properties`.
CREATE TABLE IF NOT EXISTS analytics_events (
  id              uuid PRIMARY KEY,               -- generated by the client; makes retries idempotent
  event_name      text NOT NULL,
  occurred_at     timestamptz NOT NULL,
  received_at     timestamptz NOT NULL DEFAULT now(),
  anonymous_id    text NOT NULL,
  session_id      text NOT NULL,
  user_id         text,
  is_logged_in    boolean NOT NULL DEFAULT false,
  customer_segment text,
  page_url        text,
  page_path       text,
  page_type       text,
  referrer        text,
  landing_page    text,
  utm_source      text,
  utm_medium      text,
  utm_campaign    text,
  utm_term        text,
  utm_content     text,
  source_channel  text,
  device_type     text,
  browser         text,
  os              text,
  language        text,
  country         text,
  state           text,
  city            text,
  pincode         text,
  package_slug    text,
  category        text,
  destination     text,
  properties      jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS analytics_events_name_time_idx ON analytics_events (event_name, occurred_at DESC);
CREATE INDEX IF NOT EXISTS analytics_events_session_idx ON analytics_events (session_id, occurred_at);
CREATE INDEX IF NOT EXISTS analytics_events_anon_idx ON analytics_events (anonymous_id, occurred_at);
CREATE INDEX IF NOT EXISTS analytics_events_package_idx ON analytics_events (package_slug, event_name) WHERE package_slug IS NOT NULL;

-- One row per training run of the offline ML models (ml/), shown on /dashboard.
CREATE TABLE IF NOT EXISTS ml_model_runs (
  id            bigserial PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  model         text NOT NULL,
  target        text NOT NULL,
  n_sessions    integer NOT NULL,
  n_positive    integer NOT NULL,
  n_seed        integer NOT NULL,
  include_seed  boolean NOT NULL,
  metrics       jsonb NOT NULL,
  top_features  jsonb NOT NULL,
  caveats       jsonb NOT NULL
);
